tailrec fun Context.findActivity(): Activity? = when (this) {
    is Activity -> this
    is ContextWrapper -> baseContext.findActivity()
    else -> null
}

fun attemptAutoSignIn(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onUnauthenticated: () -> Unit,
    scope: CoroutineScope
) {
    val existingUser = runCatching { Firebase.auth.currentUser }.getOrNull()
    if (existingUser != null) {
        onAuthSuccess()
        return
    }
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
        onUnauthenticated()
        return
    }
    val googleIdOption = GetGoogleIdOption.Builder()
        .setFilterByAuthorizedAccounts(true)
        .setServerClientId(clientId)
        .setAutoSelectEnabled(true)
        .build()
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()

    scope.launch {
        try {
            val activityOrContext = context.findActivity() ?: context
            val cred = credentialManager.getCredential(activityOrContext, request).credential
            if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
                Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
                onAuthSuccess()
            } else {
                onUnauthenticated()
            }
        } catch (_: Exception) {
            onUnauthenticated()
        }
    }
}

fun onGoogleSignInClicked(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onAuthError: (String) -> Unit,
    scope: CoroutineScope,
    onAuthCancelled: () -> Unit = {}
) {
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
        onAuthError("Google Sign-In কনফিগারেশন পাওয়া যায়নি (default_web_client_id)")
        return
    }
    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(signInOption)
        .build()

    scope.launch {
        try {
            val activityContext = context.findActivity() ?: context
            val cred = credentialManager.getCredential(activityContext, request).credential
            if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
                Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
                onAuthSuccess()
            } else {
                onAuthError("অপ্রত্যাশিত ক্রেডেনশিয়াল পাওয়া গেছে")
            }
        } catch (e: GetCredentialCancellationException) {
            Log.w("Auth", "Google Sign-In cancelled or dismissed: ${e.message}", e)
            onAuthCancelled()
        } catch (e: NoCredentialException) {
            Log.w("Auth", "No Google credentials found on device: ${e.message}", e)
            onAuthError("এই ডিভাইস বা এমুলেটরে কোনো Gmail/Google অ্যাকাউন্ট লগইন করা নেই। Settings থেকে Google অ্যাকাউন্ট যোগ করুন অথবা নিচের 'লগইন ছাড়া টেস্ট করুন' বাটনে চাপ দিন।")
        } catch (e: GetCredentialProviderConfigurationException) {
            Log.e("Auth", "Credential provider missing/outdated: ${e.message}", e)
            onAuthError("এই ডিভাইসে Google Play Services ক্রেডেনশিয়াল প্রোভাইডার পাওয়া যায়নি বা পুরনো। অনুগ্রহ করে Play Services আপডেট করুন অথবা নিচের টেস্ট মোড ব্যবহার করুন।")
        } catch (e: GetCredentialUnsupportedException) {
            Log.e("Auth", "Credential manager unsupported on device: ${e.message}", e)
            onAuthError("এই ডিভাইসে Credential Manager সমর্থিত নয়। নিচের 'লগইন ছাড়া সম্পূর্ণ অ্যাপ টেস্ট করুন' বাটনে চাপ দিয়ে সব ফিচার ব্যবহার করুন।")
        } catch (e: GetCredentialException) {
            Log.e("Auth", "Google Sign-In credential error: ${e.type} / ${e.message}", e)
            onAuthError("Google সাইন-ইন সম্পন্ন করা যায়নি (${e.localizedMessage ?: "নেটওয়ার্ক বা ডিভাইস ত্রুটি"})। ইন্টারনেট সংযোগ যাচাই করুন অথবা টেস্ট মোড ব্যবহার করুন।")
        } catch (e: FirebaseAuthException) {
            Log.e("Auth", "Firebase Auth error: ${e.errorCode}", e)
            onAuthError("Firebase অথেন্টিকেশন ব্যর্থ হয়েছে (${e.errorCode})। ইন্টারনেট সংযোগ ও Google অ্যাকাউন্ট যাচাই করুন।")
        } catch (e: Exception) {
            Log.e("Auth", "Google Sign-In failed", e)
            onAuthError(e.localizedMessage ?: "সাইন-ইন ব্যর্থ হয়েছে")
        }
    }
}

fun signOutUser(
    credentialManager: CredentialManager,
    scope: CoroutineScope,
    onSignOutComplete: () -> Unit = {}
) {
    scope.launch {
        withContext(NonCancellable) {
            try {
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.w("Auth", "Failed to clear credential state: ${e.message}")
            } finally {
                Firebase.auth.signOut()
                onSignOutComplete()
            }
        }
    }
}

