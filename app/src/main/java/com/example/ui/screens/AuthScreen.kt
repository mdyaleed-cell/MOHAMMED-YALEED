                        icon = Icons.Rounded.Lock,
                        title = "পিন ও বায়োমেট্রিক নিরাপত্তা",
                        subtitle = "ব্যক্তিগত বাজেট, দেনা-পাওনা ও রিপোর্ট থাকুক সম্পূর্ণ গোপন"
